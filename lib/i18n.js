const I18nContext = createContext({
  lang: 'en',
  setLang: () => {},
  t: (k) => k,
  currency: 'INR',
  setCurrency: () => {},
  formatCurrency: (n) => String(n),
});

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState('en');
  const [currency, setCurrencyState] = useState('INR');

  useEffect(() => {
    const storedLang = localStorage.getItem('pratigati_lang');
    if (storedLang === 'en' || storedLang === 'hi') {
      setLangState(storedLang);
    }
    const storedCurrency = localStorage.getItem('pratigati_currency');
    if (storedCurrency === 'INR' || storedCurrency === 'USD') {
      setCurrencyState(storedCurrency);
      setGlobalCurrency(storedCurrency);
    }
  }, []);

  const setLang = (l) => {
    setLangState(l);
    localStorage.setItem('pratigati_lang', l);
  };

  const setCurrency = (c) => {
    setCurrencyState(c);
    setGlobalCurrency(c);
    localStorage.setItem('pratigati_currency', c);
  };

  const t = (key) => translations[lang]?.[key] || translations.en[key] || key;

  const formatCurrency = (amountInINR) => formatCurrencyGlobal(amountInINR, currency);

  return (
    <I18nContext.Provider value={{ lang, setLang, t, currency, setCurrency, formatCurrency }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);
