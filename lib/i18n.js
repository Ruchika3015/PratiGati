const USD_TO_INR = 83;

let _currency = 'INR';

export function getCurrency() {
  return _currency;
}

export function setGlobalCurrency(c) {
  _currency = c;
}

export function formatCurrencyGlobal(amountInINR, currency) {
  if (amountInINR == null || isNaN(amountInINR)) return '—';
  const num = Number(amountInINR);
  const cur = currency || _currency;

  if (cur === 'USD') {
    const usd = num / USD_TO_INR;
    if (usd >= 1000000) return `$${(usd / 1000000).toFixed(2)}M`;
    if (usd >= 10000) return `$${(usd / 1000).toFixed(1)}K`;
    if (usd >= 1000) return `$${(usd / 1000).toFixed(2)}K`;
    return `$${usd.toFixed(2)}`;
  }

  if (num >= 10000000) return `₹${(num / 10000000).toFixed(2)}Cr`;
  if (num >= 100000) return `₹${(num / 100000).toFixed(2)}L`;
  if (num >= 10000) return `₹${(num / 1000).toFixed(0)}K`;
  return `₹${num.toLocaleString('en-IN')}`;
}

